"""Builds the installable web app (PWA) into web/ from the main game file.
Usage: python3 tools/build_web.py   (run from the project root after each release)
- copies app/src/main/assets/index.html to web/index.html and adds the web-app <head> tags
- writes manifest.webmanifest and sw.js, stamping the game's VERSION into the offline cache name"""
import json, pathlib, re
root=pathlib.Path(__file__).resolve().parent.parent
src=(root/'app/src/main/assets/index.html').read_text(encoding='utf-8')
version=re.search(r"const VERSION='([\d.]+)'",src).group(1)
head_tags='''<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" sizes="32x32" href="favicon-32.png">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="Colour Basher">
<meta name="description" content="Bash the target colour as fast as you can. A Japanese-arcade style colour puzzle.">
'''
assert '<title>Colour Basher</title>' in src
web=src.replace('<title>Colour Basher</title>','<title>Colour Basher</title>\n'+head_tags,1)
(root/'web/index.html').write_text(web,encoding='utf-8')
manifest={
 "name":"Colour Basher","short_name":"Colour Basher","id":"./","start_url":"./","scope":"./",
 "display":"fullscreen","display_override":["fullscreen","standalone"],"orientation":"portrait",
 "background_color":"#140d3a","theme_color":"#140d3a","categories":["games"],
 "description":"Bash the target colour as fast as you can. A Japanese-arcade style colour puzzle.",
 "icons":[
  {"src":"icon-192.png","sizes":"192x192","type":"image/png","purpose":"any"},
  {"src":"icon-512.png","sizes":"512x512","type":"image/png","purpose":"any"},
  {"src":"icon-maskable-512.png","sizes":"512x512","type":"image/png","purpose":"maskable"}]}
(root/'web/manifest.webmanifest').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
sw='''/* Colour Basher service worker: offline play. Generated by tools/build_web.py - do not edit by hand. */
const CACHE='colour-basher-%s';
const CORE=['./','index.html','manifest.webmanifest','icon-192.png','icon-512.png','icon-maskable-512.png','apple-touch-icon.png','favicon-32.png'];
self.addEventListener('install',e=>{e.waitUntil(caches.open(CACHE).then(c=>c.addAll(CORE)).then(()=>self.skipWaiting()));});
self.addEventListener('activate',e=>{e.waitUntil(caches.keys().then(ks=>Promise.all(ks.filter(k=>k.startsWith('colour-basher-')&&k!==CACHE).map(k=>caches.delete(k)))).then(()=>self.clients.claim()));});
self.addEventListener('fetch',e=>{
  const r=e.request;if(r.method!=='GET')return;
  if(r.mode==='navigate'){   // the game page: newest version when online, cached copy when offline
    e.respondWith(fetch(r).then(res=>{const copy=res.clone();caches.open(CACHE).then(c=>c.put('index.html',copy));return res;})
      .catch(()=>caches.match('index.html')));return;}
  e.respondWith(caches.match(r).then(hit=>hit||fetch(r).then(res=>{   // icons, fonts: cache first
    if(res.ok||res.type==='opaque'){const copy=res.clone();caches.open(CACHE).then(c=>c.put(r,copy));}return res;})));
});
'''%version
(root/'web/sw.js').write_text(sw,encoding='utf-8')
print('web app built for version',version)
